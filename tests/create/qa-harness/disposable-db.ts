/**
 * Teardown for the disposable databases created by the *.db.test.ts suites.
 *
 * Why not pg_terminate_backend + DROP DATABASE:
 *   Through the Supabase Session Pooler (Supavisor), the pooler keeps its own
 *   server connection to the disposable database after the test's Pool has
 *   ended. pg_terminate_backend only signals — it does not wait — and nothing
 *   stops the pooler from holding or re-opening a connection before the DROP,
 *   so DROP DATABASE intermittently fails with 55006 ("being accessed by other
 *   users") and the database is orphaned.
 *
 * DROP DATABASE ... WITH (FORCE) (PostgreSQL 13+) takes the database lock,
 * terminates remaining sessions and waits for them to exit as one operation.
 * A bounded retry covers any residual 55006; every other error, exhausted
 * retries, or a database still present afterwards throws — cleanup failure is
 * never swallowed.
 */

/** Only names generated by the builder DB suites may ever be dropped. */
const DISPOSABLE_DB_NAME = /^_(kebtest_(authz|rls|kcd)|kebutest)_[a-z0-9]{1,8}$/;

const OBJECT_IN_USE = "55006";
const MAX_ATTEMPTS = 4;
const BASE_DELAY_MS = 250;

interface QueryablePool {
  connect(): Promise<{
    query(sql: string, values?: unknown[]): Promise<{ rows: Record<string, unknown>[]; rowCount: number | null }>;
    release(): void;
  }>;
}

export function assertDisposableDbName(name: string): void {
  if (!DISPOSABLE_DB_NAME.test(name)) {
    throw new Error(
      `disposable-db: refusing to drop "${name}" — name does not match the disposable test-database pattern ${DISPOSABLE_DB_NAME}`
    );
  }
}

export async function dropDisposableDatabase(adminPool: QueryablePool, name: string): Promise<void> {
  assertDisposableDbName(name);

  const c = await adminPool.connect();
  try {
    const { rows } = await c.query(`SELECT current_database() AS db`);
    if (rows[0]?.db === name) {
      throw new Error(`disposable-db: refusing to drop "${name}" — it is the admin connection's current database`);
    }

    for (let attempt = 1; ; attempt++) {
      try {
        await c.query(`DROP DATABASE IF EXISTS "${name}" WITH (FORCE)`);
        break;
      } catch (err) {
        const code = (err as { code?: string }).code;
        if (code !== OBJECT_IN_USE || attempt >= MAX_ATTEMPTS) {
          throw new Error(
            `disposable-db: DROP DATABASE "${name}" failed after ${attempt} attempt(s): ${(err as Error).message}`,
            { cause: err }
          );
        }
        await new Promise((r) => setTimeout(r, BASE_DELAY_MS * 2 ** (attempt - 1)));
      }
    }

    const remaining = await c.query(`SELECT 1 FROM pg_database WHERE datname = $1`, [name]);
    if (remaining.rowCount) {
      throw new Error(`disposable-db: "${name}" still exists after DROP DATABASE`);
    }
  } finally {
    c.release();
  }
}

interface EndablePool {
  end(): Promise<void>;
}

const POOL_END_TIMEOUT_MS = 10_000;

/**
 * pool.end() waits for every checked-out client. A test that timed out while
 * awaiting a blocked query never reaches its finally block, so its client is
 * never returned and pool.end() would wait forever. Bound it and report it.
 */
async function endPoolWithin(pool: EndablePool, label: string): Promise<void> {
  let timer: ReturnType<typeof setTimeout> | undefined;
  try {
    await Promise.race([
      pool.end(),
      new Promise<never>((_, reject) => {
        timer = setTimeout(
          () => reject(new Error(`disposable-db: ${label}.end() did not finish within ${POOL_END_TIMEOUT_MS}ms — a client was still checked out`)),
          POOL_END_TIMEOUT_MS,
        );
      }),
    ]);
  } finally {
    clearTimeout(timer);
  }
}

/**
 * Bounded, fail-visible afterAll for the disposable-database suites.
 * The database is always dropped — even when the test pool could not be ended,
 * WITH (FORCE) terminates whatever sessions it left behind — and every error
 * encountered along the way is rethrown once cleanup has finished.
 */
export async function teardownDisposableDatabase(opts: {
  pools: (EndablePool | undefined)[];
  adminPool: (EndablePool & QueryablePool) | undefined;
  name: string;
}): Promise<void> {
  const errors: Error[] = [];
  const record = (err: unknown) => errors.push(err instanceof Error ? err : new Error(String(err)));

  for (const [i, pool] of opts.pools.entries()) {
    if (pool) await endPoolWithin(pool, `test pool #${i}`).catch(record);
  }
  if (opts.adminPool) {
    await dropDisposableDatabase(opts.adminPool, opts.name).catch(record);
    await endPoolWithin(opts.adminPool, "admin pool").catch(record);
  }

  if (errors.length) {
    throw new Error(
      `disposable-db: teardown of "${opts.name}" failed:\n` + errors.map((e) => `  • ${e.message}`).join("\n"),
      { cause: errors[0] },
    );
  }
}
